"""
Qwen inference module.

Runs actual inference through the Qwen2.5-0.5B-Instruct base model
with the specified LoRA adapter (agent1, agent2, or global_qwen).

NO hardcoded responses. All text is generated by the actual model.
"""
import time
import logging
import threading
import torch
from typing import Optional

logger = logging.getLogger(__name__)

# Lock to prevent concurrent adapter switching on the shared model
_inference_lock = threading.Lock()


def generate_qwen_response(
    model_manager,
    adapter_name: str,
    system_prompt: str,
    user_message: str,
    max_new_tokens: int = 320,
    temperature: float = 0.2,
    top_p: float = 0.85,
    repetition_penalty: float = 1.18,
) -> dict:
    """
    Generate a response using the Qwen model with the specified LoRA adapter.

    Args:
        model_manager: The ModelManager instance with loaded models
        adapter_name: Which adapter to use ("agent1", "agent2", "global_qwen")
        system_prompt: The system/role prompt for this agent
        user_message: The user's question + context
        max_new_tokens: Maximum tokens to generate
        temperature: Sampling temperature
        top_p: Top-p sampling
        repetition_penalty: Penalty for repeated tokens

    Returns:
        dict with "text", "generation_time_ms", "input_tokens", "output_tokens"
    """
    with _inference_lock:
        # Switch to the correct adapter
        model_manager.set_adapter(adapter_name)

        model = model_manager.base_model
        tokenizer = model_manager.tokenizer

        # Build chat messages using the Qwen chat template
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_message},
        ]

        # Apply chat template
        text = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True,
        )

        inputs = tokenizer(text, return_tensors="pt", truncation=True, max_length=2048)
        input_ids = inputs["input_ids"].to(model.device)
        attention_mask = inputs["attention_mask"].to(model.device)
        input_length = input_ids.shape[1]

        start = time.time()

        with torch.no_grad():
            outputs = model.generate(
                input_ids=input_ids,
                attention_mask=attention_mask,
                max_new_tokens=max_new_tokens,
                temperature=temperature,
                top_p=top_p,
                repetition_penalty=repetition_penalty,
                no_repeat_ngram_size=3,
                do_sample=True if temperature > 0.05 else False,
                pad_token_id=tokenizer.pad_token_id,
            )

        generation_time_ms = (time.time() - start) * 1000.0

        # Decode only the new tokens
        new_tokens = outputs[0][input_length:]
        generated_text = tokenizer.decode(new_tokens, skip_special_tokens=True)

        result = {
            "text": generated_text.strip(),
            "generation_time_ms": generation_time_ms,
            "input_tokens": input_length,
            "output_tokens": len(new_tokens),
            "adapter_used": adapter_name,
        }

        logger.info(
            f"Qwen inference [{adapter_name}]: "
            f"{input_length} input tokens → {len(new_tokens)} output tokens "
            f"in {generation_time_ms:.0f}ms"
        )

        return result


def get_logits_for_jev(
    model_manager,
    adapter_name: str,
    prompt_text: str,
) -> dict:
    """
    Get raw logits from the model's last position for JEV decision-head processing.

    This passes the Qwen explanation through the model and extracts
    the next-token logits needed by the JEV decision head.

    Returns:
        dict with "logits" (tensor), "time_ms"
    """
    with _inference_lock:
        model_manager.set_adapter(adapter_name)

        model = model_manager.base_model
        tokenizer = model_manager.tokenizer

        inputs = tokenizer(prompt_text, return_tensors="pt", truncation=True, max_length=2048)
        input_ids = inputs["input_ids"].to(model.device)
        attention_mask = inputs["attention_mask"].to(model.device)

        start = time.time()

        with torch.no_grad():
            outputs = model(
                input_ids=input_ids,
                attention_mask=attention_mask,
            )
            # Get logits at the last position
            last_logits = outputs.logits[0, -1, :]  # shape: [vocab_size]

        elapsed_ms = (time.time() - start) * 1000.0

        return {
            "logits": last_logits,
            "time_ms": elapsed_ms,
        }
